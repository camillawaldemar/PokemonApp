"""
Turns pokemon.csv into data.js, the single data file the website loads.

Run:  python3 build_data.py

All 811 rows are kept: 721 species and 90 alternate forms. The forms carry no
generation, evolution chain or image in the CSV, but they do belong to a species
through species_id, and the site pairs them with that species. Images for all of
them come from the API at runtime.
"""

import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "pokemon.csv")
OUT = os.path.join(HERE, "data.js")

STATS = ["hp", "attack", "defense", "special_attack", "special_defense", "speed"]


def clean(value):
    value = (value or "").strip()
    return None if value in ("", "NA") else value


def main():
    with open(SRC, encoding="utf-8-sig", newline="") as handle:
        rows = list(csv.DictReader(handle))

    out = []

    for r in rows:
        is_species = clean(r["generation_id"]) is not None
        name = r["pokemon"]
        if is_species:
            kind = "species"
        elif "-mega" in name:
            kind = "mega"
        elif "-primal" in name:
            kind = "primal"
        else:
            kind = "form"

        out.append({
            "id": int(r["id"]),
            "species": int(r["species_id"]),
            "kind": kind,
            "name": r["pokemon"],
            "types": [t for t in (clean(r["type_1"]), clean(r["type_2"])) if t],
            "typeColors": [c for c in (clean(r["color_1"]), clean(r["color_2"])) if c],
            "accent": clean(r["color_f"]) or "#6B7488",
            "stats": [int(r[s]) for s in STATS],
            "height": int(r["height"]),
            "weight": int(r["weight"]),
            "baseExp": int(r["base_experience"]) if clean(r["base_experience"]) else None,
            "abilities": [a for a in (clean(r["ability_1"]), clean(r["ability_2"])) if a],
            "hiddenAbility": clean(r["ability_hidden"]),
            "eggGroups": [g for g in (clean(r["egg_group_1"]), clean(r["egg_group_2"])) if g],
            "shape": clean(r["shape"]),
            "generation": int(r["generation_id"]) if is_species else None,
            "image": clean(r["url_image"]),
            "evolvesFrom": int(r["evolves_from_species_id"]) if clean(r["evolves_from_species_id"]) else None,
            "chain": int(r["evolution_chain_id"]) if clean(r["evolution_chain_id"]) else None,
        })

    out.sort(key=lambda p: p["id"])
    payload = json.dumps(out, separators=(",", ":"), ensure_ascii=False)

    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write("// Generated by build_data.py from pokemon.csv. Do not edit by hand.\n")
        handle.write("const POKEMON = " + payload + ";\n")

    kinds = {}
    for p in out:
        kinds[p["kind"]] = kinds.get(p["kind"], 0) + 1

    print(f"wrote {OUT}")
    print(f"  entries: {len(out)}")
    for k in sorted(kinds):
        print(f"    {k}: {kinds[k]}")
    print(f"  with an evolution: {sum(1 for p in out if p['evolvesFrom'])}")
    print(f"  without image data in the CSV: {sum(1 for p in out if not p['image'])}"
          " (the API covers these)")


if __name__ == "__main__":
    main()
